const glyph = ch => G[ch] || G[ch.toUpperCase()] || G["?"];

// Width in dots of text at a size (scale), with one dot between letters
export function pixelTextWidth(text, scale) {
    let w = 0;
    for (const ch of text) w += (glyph(ch)[0].length + 1) * scale;
    return Math.max(0, w - scale);
}

// Draws into a picture (rows of booleans); x, y = top-left in dots; bold = one extra dot to the right
export function drawPixelText(pix, text, x, y, scale, on = true, bold = false) {
    const width = pix[0].length, height = pix.length;
    for (const ch of text) {
        const g = glyph(ch);
        g.forEach((row, ry) => [...row].forEach((c, rx) => {
            if (c !== "1") return;
            for (let a = 0; a < scale + (bold ? 1 : 0); a++) for (let d = 0; d < scale; d++) {
                const px = Math.round(x + rx * scale + a), py = Math.round(y + ry * scale + d);
                if (px >= 0 && px < width && py >= 0 && py < height) pix[py][px] = on;
            }
        }));
        x += (g[0].length + 1) * scale;
    }
}
